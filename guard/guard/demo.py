"""A synthetic app that fails all three checks, on purpose.

Two reasons this exists instead of pointing the reader at a real repository:

* a real repository has one, maybe two, of these bugs, so the demo would be
  unconvincing;
* committing a key-shaped string to demonstrate a key leak is how you get your
  GitHub account flagged.

So the tree is generated at runtime, never committed, and every credential in it
is a repeating ``demo`` pattern (no real provider could ever issue it).
"""

from __future__ import annotations

import json
from pathlib import Path

# `len(set()) == 4` in the placeholder heuristic, so this is detected as a key
# — while being obviously synthetic to a human and worthless to any API.
DEMO_KEY = "sk-proj-" + "demo" * 12

_WIDGET_JS = """\
// Chat widget: bundled and shipped to every visitor of the landing page.
const OPENAI_KEY = "%s";

export async function ask(prompt) {
  const response = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${OPENAI_KEY}` },
    body: JSON.stringify({ model: "gpt-4o-mini", messages: [{ role: "user", content: prompt }] }),
  });
  return (await response.json()).choices[0].message.content;
}
"""

_AGENT_PY = """\
import json

from openai import OpenAI

client = OpenAI()


def stream_answer(prompt: str):
    \"\"\"Keep trying until the model answers. It always answers eventually.\"\"\"
    while True:
        try:
            completion = client.chat.completions.create(
                model="gpt-4o-mini",
                messages=[{"role": "user", "content": prompt}],
                stream=True,
            )
            for chunk in completion:
                delta = chunk.choices[0].delta.content
                if delta:
                    yield delta
        except Exception:
            continue


if __name__ == "__main__":
    for token in stream_answer("hello"):
        print(json.dumps({"delta": token}))
"""

_MCP_JSON = {
    "mcpServers": {
        "terminal": {"command": "npx", "args": ["-y", "@modelcontextprotocol/server-shell"],
                     "allowedTools": ["*"]},
        "notes": {"command": "node", "args": ["notes-server.js"]},
    }
}

_SETTINGS_JSON = {"dangerouslySkipPermissions": True, "model": "sonnet"}


def build_tree(root: str | Path) -> Path:
    target = Path(root)
    (target / "public").mkdir(parents=True, exist_ok=True)
    (target / "app").mkdir(parents=True, exist_ok=True)
    (target / ".claude").mkdir(parents=True, exist_ok=True)

    (target / "public" / "widget.js").write_text(_WIDGET_JS % DEMO_KEY, encoding="utf-8")
    (target / "app" / "agent.py").write_text(_AGENT_PY, encoding="utf-8")
    (target / "mcp.json").write_text(json.dumps(_MCP_JSON, indent=2), encoding="utf-8")
    (target / ".claude" / "settings.json").write_text(
        json.dumps(_SETTINGS_JSON, indent=2), encoding="utf-8"
    )
    (target / "README.md").write_text(
        "# demo app\n\nGenerated by `python -m guard.cli demo`. Not a real project.\n",
        encoding="utf-8",
    )
    return target
